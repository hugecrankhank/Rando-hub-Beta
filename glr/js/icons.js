  // Same icons as <img> sources for canvas drawing.
  const imgCache = {};
  function image(name) {
    if (imgCache[name]) return imgCache[name];
    const im = new Image();
    im.src = 'data:image/svg+xml,' + encodeURIComponent(svg(name).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" '));
    return (imgCache[name] = im);
  }

