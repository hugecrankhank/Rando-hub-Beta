  const cache = {};
  function svg(name) {
    if (cache[name]) return cache[name];
    const art = ART[name];
    if (!art) return '';
    let rects = '';
    for (let y = 0; y < 16; y++) {
      const row = art[y] || '';
      let x = 0;
      while (x < 16) {
        const ch = row[x];
        if (!ch || ch === '.') { x++; continue; }
        let w = 1;
        while (row[x + w] === ch) w++;
        rects += '<rect x="' + x + '" y="' + y + '" width="' + w + '" height="1" fill="' + (PAL[ch] || '#f0f') + '"/>';
        x += w;
      }
    }
    return (cache[name] = '<svg viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">' + rects + '</svg>');
  }
  const kind = (k) => svg(KIND_ART[k]);
