      GT = [0.915, 1.086, 0.98, 1.026, 0.908, 0.987, 0.75],
      BT = [0.743, 0.882, 0.653, 1.277, 0.979, 0.101, 0.75];
  function clamp(v) { return v > 255 ? 255 : v | 0; }
  // the colour of palette entry i (0..511: index + emphasis bits << 6)
  function entry(pal, i, mesen) {
    var c = pal[i & 63], r = c >> 16 & 255, g = c >> 8 & 255, b = c & 255, e = i >> 6;
    if (e) {
      if (mesen) {
        if ((i & 15) <= 13) {
          if (e & 1) { g *= 0.84; b *= 0.84; }
          if (e & 2) { r *= 0.84; b *= 0.84; }
          if (e & 4) { r *= 0.84; g *= 0.84; }
        }
      } else { r *= RT[e - 1]; g *= GT[e - 1]; b *= BT[e - 1]; }
    }
    return [clamp(r), clamp(g), clamp(b)];
  }
